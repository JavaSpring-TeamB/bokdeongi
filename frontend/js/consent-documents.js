    function get(type) {
        return DOCUMENTS[type] || null;
    }

    function versionFor(type) {
        return get(type)?.version || null;
    }

    function renderInto(container, type) {
        const documentInfo = get(type);
        if (!container || !documentInfo) return null;

        container.replaceChildren();
        const version = document.createElement('p');
        version.className = 'consent-document__version';
        version.textContent = `문서 버전: ${documentInfo.version}`;
        container.append(version);

        documentInfo.sections.forEach(([heading, paragraphs]) => {
            const section = document.createElement('section');
            section.className = 'consent-document__section';
            const title = document.createElement('h3');
            title.textContent = heading;
            section.append(title);
            paragraphs.forEach((text) => {
                const paragraph = document.createElement('p');
                paragraph.textContent = text;
                section.append(paragraph);
            });
            container.append(section);
        });
        return documentInfo;
    }

