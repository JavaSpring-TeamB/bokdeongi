import pytest

from app.masking import MaskingError, mask, mask_lines


@pytest.mark.parametrize("raw, want", [
    ("주민등록번호 900101-1234567", "주민등록번호 900101-1******"),
    ("900101 - 2234567 홍길동", "900101-2****** 홍길동"),   # OCR이 띄어 읽은 경우
    ("9001012234567", "900101-2******"),                    # 하이픈 없이
    ("900101-1******", "900101-1******"),                   # 이미 가려진 등본
    ("0900505-1234567", "0900505-1******"),                 # 앞에 숫자가 더 붙어 읽힌 경우(실제 OCR 결과)
    ("召910101-2345678", "召910101-2******"),
])
def test_주민번호_뒷자리(raw, want):
    assert mask(raw) == want


def test_전화번호():
    assert mask("연락처 010-1234-5678") == "연락처 010-****-5678"
    assert mask("01012345678") == "010-****-5678"
    assert mask("02-123-4567") == "02-***-4567"


def test_계좌번호는_끝_4자리만():
    assert mask("계좌 110-123-456789") == "계좌 ***-***-**6789"


def test_날짜와_금액은_그대로():
    text = "발급일 2026-11-16 보험료 123,450원 2026.10.01"
    assert mask(text) == text


def test_줄을_넘는_주민번호는_실패():
    with pytest.raises(MaskingError):
        mask_lines(["주민등록번호 900101", "-1234567"])


def test_상세주소만_가린다():
    assert mask("서울특별시 광진구 가상로 12, 101호") == "서울특별시 광진구 가상로 12, ***호"
    assert mask("가상아파트 101동 1203호") == "가상아파트 ***동 ****호"
    assert mask("광진1동 주민센터, 제3호 서식, 2호선 역") == "광진1동 주민센터, 제3호 서식, 2호선 역"


def test_하이픈_없는_계좌도_끝_4자리만():
    assert mask("가상계좌 56202012345678") == "가상계좌 **********5678"
    assert mask("월 1,833,000원 / 20261231 / 1833000원") == "월 1,833,000원 / 20261231 / 1833000원"
